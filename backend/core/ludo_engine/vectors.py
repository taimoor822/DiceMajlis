# name, rules, timeout chance (per 1000 actions)
_PRESETS: list[tuple[str, Rules, int]] = [
    ("standard", Rules(), 15),
    ("ranking", Rules(end_when_first_player_finishes=False), 15),
    ("quick", Rules(tokens_per_player=2, entry_rolls=frozenset({1, 6})), 20),
    ("no-captures", Rules(capture_enabled=False), 15),
    ("no-safe-squares", Rules(safe_squares=frozenset()), 15),
    (
        "no-extra-turns",
        Rules(
            extra_turn_on_six=False,
            extra_turn_on_capture=False,
            extra_turn_on_finish=False,
            max_consecutive_sixes=0,
        ),
        15,
    ),
    ("strict", Rules(max_consecutive_sixes=2, max_missed_turns=1), 25),
    (
        "single-token",
        Rules(tokens_per_player=1, end_when_first_player_finishes=False),
        20,
    ),
    ("patient", Rules(max_missed_turns=0), 150),
    (
        "open-entry",
        Rules(entry_rolls=frozenset(range(1, 7)), end_when_first_player_finishes=False),
        15,
    ),
]

FULL_GAMES = ["standard", "ranking", "quick", "single-token"]
MIDGAMES_PER_PRESET = 2
FORFEIT_CHANCE = 1  # per 1000 actions
PROBE_CHANCE = 30  # per 1000 actions: try something the engine must refuse


def build_vectors() -> dict[str, Any]:
    presets = {name: (rules, timeouts) for name, rules, timeouts in _PRESETS}
    games = []
    seed = 0
    # Whole games from the first roll...
    for name in FULL_GAMES:
        rules, timeouts = presets[name]
        games.append(_play(f"{name}-{seed}", seed, rules, timeouts, from_start=True))
        seed += 1
    # ...and many games from random mid-game positions: captures, home columns,
    # finishing places and endings come up far more often per step.
    for name, (rules, timeouts) in presets.items():
        for _ in range(MIDGAMES_PER_PRESET):
            games.append(_play(f"{name}-{seed}", seed, rules, timeouts, from_start=False))
            seed += 1
    return {
        "format": FORMAT,
        "about": (
            "Generated by backend/core/ludo_engine/vectors.py from the Python engine. "
            "Do not edit by hand: run `python -m ludo_engine.vectors` in backend/core. "
            "Events are [type, data]; every event of a step carries version = the "
            "version before the step + 1."
        ),
        "board": _board(),
        "default_rules": Rules().to_dict(),
        "setups": _setups(),
        "snapshots": _snapshots(),
        "games": games,
    }


def _board() -> dict[str, Any]:
    return {
        "track_length": board.TRACK_LENGTH,
        "seat_count": board.SEAT_COUNT,
        "seat_spacing": board.SEAT_SPACING,
        "base_progress": board.BASE_PROGRESS,
        "start_progress": board.START_PROGRESS,
        "last_track_progress": board.LAST_TRACK_PROGRESS,
        "first_home_column_progress": board.FIRST_HOME_COLUMN_PROGRESS,
        "home_progress": board.HOME_PROGRESS,
        "seat_colors": list(board.SEAT_COLORS),
        "default_safe_squares": sorted(board.default_safe_squares()),
        "default_seats": {str(n): list(board.default_seats_for(n)) for n in (2, 3, 4)},
        # absolute_square[seat][progress + 1], for progress -1..56
        "absolute_square": [
            [board.absolute_square(seat, p) for p in range(board.BASE_PROGRESS, board.HOME_PROGRESS + 1)]
            for seat in range(board.SEAT_COUNT)
        ],
    }


def _setups() -> list[dict[str, Any]]:
    cases: list[tuple[str, dict[str, Any]]] = [
        ("two players sit opposite", {"player_ids": ["a", "b"]}),
        ("three players", {"player_ids": ["a", "b", "c"]}),
        ("four players", {"player_ids": ["a", "b", "c", "d"]}),
        ("chosen seats are sorted into turn order", {"player_ids": ["x", "y"], "seats": [3, 1]}),
        ("first player", {"player_ids": ["a", "b", "c"], "seats": [2, 0, 3], "first_player_id": "c"}),
        ("custom rules", {"player_ids": ["a", "b"], "rules": Rules(tokens_per_player=2).to_dict()}),
        ("one player", {"player_ids": ["a"]}),
        ("five players", {"player_ids": ["a", "b", "c", "d", "e"]}),
        ("duplicate ids", {"player_ids": ["a", "a"]}),
        ("duplicate seats", {"player_ids": ["a", "b"], "seats": [1, 1]}),
        ("seat out of range", {"player_ids": ["a", "b"], "seats": [0, 4]}),
        ("negative seat", {"player_ids": ["a", "b"], "seats": [-1, 2]}),
        ("one seat per player", {"player_ids": ["a", "b", "c"], "seats": [0, 1]}),
        ("unknown first player", {"player_ids": ["a", "b"], "first_player_id": "z"}),
    ]
    out = []
    for name, args in cases:
        kwargs: dict[str, Any] = {}
        if "seats" in args:
            kwargs["seats"] = args["seats"]
        if "rules" in args:
            kwargs["rules"] = Rules.from_dict(args["rules"])
        if "first_player_id" in args:
            kwargs["first_player_id"] = args["first_player_id"]
        case: dict[str, Any] = {"name": name, "game_id": "setup", **args}
        try:
            case["state"] = new_game("setup", args["player_ids"], **kwargs).to_dict()
        except EngineError as error:
            case["error"] = error.code
        out.append(case)
    return out


def _snapshots() -> list[dict[str, Any]]:
    """Stored states the engine must refuse to load (tampered or impossible)."""
    good = new_game("snap", ["a", "b"]).to_dict()

    def changed(change: Callable[[dict[str, Any]], None]) -> dict[str, Any]:
        data = json.loads(json.dumps(good))
        change(data)
        return data

    cases = [
        ("valid", good),
        ("unknown schema version", changed(lambda d: d.update(schema_version=99))),
        ("unknown current player", changed(lambda d: d.update(current_player_id="z"))),
        ("one player", changed(lambda d: d["players"].pop())),
        ("duplicate player ids", changed(lambda d: d["players"][1].update(player_id="a"))),
        ("seats out of order", changed(lambda d: d["players"].reverse())),
        ("too many tokens", changed(lambda d: d["players"][0]["tokens"].append({"progress": -1}))),
        ("token off the board", changed(lambda d: d["players"][0]["tokens"][0].update(progress=57))),
        ("move without dice", changed(lambda d: d.update(phase="awaiting_move"))),
        ("dice while awaiting roll", changed(lambda d: d.update(dice_value=3))),
        ("negative version", changed(lambda d: d.update(version=-1))),
    ]
    out = []
    for name, data in cases:
        case: dict[str, Any] = {"name": name, "json": data}
        try:
            case["state"] = GameState.from_dict(data).to_dict()
        except EngineError as error:
            case["error"] = error.code
        out.append(case)
    return out


