def _play(
    name: str, seed: int, rules: Rules, timeout_chance: int, *, from_start: bool
) -> dict[str, Any]:
    rng = _Rng(seed)
    count = 2 + rng.below(3)
    ids = [f"{name[0]}{seed}-{i}" for i in range(count)]
    seats: list[int] | None = None
    if not from_start or rng.per_mille(500):
        pool = list(range(board.SEAT_COUNT))
        for i in range(len(pool) - 1, 0, -1):  # shuffle, then take the first `count`
            j = rng.below(i + 1)
            pool[i], pool[j] = pool[j], pool[i]
        seats = pool[:count]

    setup: dict[str, Any] | None = None
    if from_start:
        setup = {"game_id": name, "player_ids": ids, "rules": rules.to_dict()}
        if seats is not None:
            setup["seats"] = seats
        if rng.per_mille(400):
            setup["first_player_id"] = rng.choice(ids)
        state = new_game(
            name,
            ids,
            seats=seats,
            rules=rules,
            first_player_id=setup.get("first_player_id"),
        )
    else:
        assert seats is not None
        state = _random_position(name, ids, seats, rules, rng)
    initial = state
    steps: list[dict[str, Any]] = []
    accepted = 0
    while state.status is GameStatus.PLAYING:
        if len(steps) >= MAX_ACTIONS:
            raise RuntimeError(f"vector game {name} did not finish")
        if rng.per_mille(PROBE_CHANCE):
            action = _probe(state, rng)
        else:
            action = _next_action(state, rng, timeout_chance)
        step: dict[str, Any] = {"action": action}
        before = state
        try:
            transition = apply_action(state, action)
        except EngineError as error:
            step["error"] = error.code
            steps.append(step)
            continue
        if before.phase is TurnPhase.AWAITING_MOVE:
            step["bot"] = choose_move(before).token_index
        step["events"] = [[e.type.value, e.data] for e in transition.events]
        state = transition.state
        accepted += 1
        if accepted % CHECKPOINT_EVERY == 0:
            step["state"] = state.to_dict()
        steps.append(step)

    # A finished game refuses everything.
    for action in (
        {"type": "roll", "player_id": ids[0], "value": 6},
        {"type": "timeout", "dice_value": 3},
        {"type": "forfeit", "player_id": ids[-1]},
    ):
        try:
            apply_action(state, action)
        except EngineError as error:
            steps.append({"action": action, "error": error.code})
        else:  # pragma: no cover - the engine must refuse these
            raise RuntimeError("a finished game accepted an action")

    game: dict[str, Any] = {"name": name}
    if setup is not None:
        game["setup"] = setup
    return {
        **game,
        "initial": initial.to_dict(),
        "steps": steps,
        "final": state.to_dict(),
    }


def _random_position(
    name: str, ids: list[str], seats: list[int], rules: Rules, rng: _Rng
) -> GameState:
    """A believable mid-game position: tokens spread out, no two opponents on
    one unsafe square, sometimes a player already finished or gone."""
    order = sorted(range(len(ids)), key=lambda i: seats[i])
    taken: dict[int, int] = {}  # unsafe square -> seat standing on it
    players = []
    for i in order:
        seat = seats[i]
        tokens = []
        for _ in range(rules.tokens_per_player):
            while True:
                roll = rng.below(100)
                if roll < 20:
                    progress = board.BASE_PROGRESS
                elif roll < 30:
                    progress = board.FIRST_HOME_COLUMN_PROGRESS + rng.below(board.HOME_COLUMN_LENGTH)
                elif roll < 36:
                    progress = board.HOME_PROGRESS
                else:
                    progress = rng.below(board.LAST_TRACK_PROGRESS + 1)
                square = board.absolute_square(seat, progress)
                if square is None or square in rules.safe_squares or taken.get(square, seat) == seat:
                    break
            if square is not None and square not in rules.safe_squares:
                taken[square] = seat
            tokens.append(progress)
        if all(p == board.HOME_PROGRESS for p in tokens):
            tokens[0] = board.LAST_TRACK_PROGRESS + 1  # not finished yet
        missed = rng.below(rules.max_missed_turns) if rules.max_missed_turns else rng.below(3)
        players.append(PlayerState(ids[i], seat, tuple(tokens), missed_turns=missed))

    # Sometimes someone is already out of the race (needs 3+ players left after).
    if len(players) >= 3 and rng.per_mille(500):
        k = rng.below(len(players))
        if rng.per_mille(500) and not rules.end_when_first_player_finishes:
            home = tuple(board.HOME_PROGRESS for _ in players[k].tokens)
            players[k] = replace(players[k], tokens=home, status=PlayerStatus.FINISHED,
                                 finish_place=1, missed_turns=0)
        else:
            players[k] = replace(players[k], status=PlayerStatus.FORFEITED,
                                 finish_place=len(players), missed_turns=0)

    active = [i for i, p in enumerate(players) if p.status is PlayerStatus.ACTIVE]
    sixes = rng.below(rules.max_consecutive_sixes) if rules.max_consecutive_sixes else rng.below(3)
    return GameState(
        game_id=name,
        players=tuple(players),
        rules=rules,
        current_index=rng.choice(active),
        turn_number=1 + rng.below(300),
        consecutive_sixes=sixes,
        version=rng.below(1000),
    )


def _next_action(state: GameState, rng: _Rng, timeout_chance: int) -> dict[str, Any]:
    current = state.current_player.player_id
    if rng.per_mille(timeout_chance):
        return {"type": "timeout", "dice_value": rng.die(), "turn_number": state.turn_number}
    if rng.per_mille(FORFEIT_CHANCE):
        active = [p.player_id for p in state.players if p.status is PlayerStatus.ACTIVE]
        return {"type": "forfeit", "player_id": rng.choice(active), "reason": "left"}
    if state.phase is TurnPhase.AWAITING_ROLL:
        return {"type": "roll", "player_id": current, "value": rng.die()}
    if rng.per_mille(500):
        token = choose_move(state).token_index
    else:
        token = rng.choice(list(legal_moves(state))).token_index
    return {"type": "move", "player_id": current, "token_index": token}


def _probe(state: GameState, rng: _Rng) -> dict[str, Any]:
    """An action the engine should refuse (it is recorded either way)."""
    current = state.current_player.player_id
    others = [p.player_id for p in state.players if p.player_id != current]
    movable = {m.token_index for m in legal_moves(state)}
    stuck = [i for i in range(state.rules.tokens_per_player) if i not in movable]
    out = [p.player_id for p in state.players if p.status is not PlayerStatus.ACTIVE]
    options: list[dict[str, Any]] = [
        {"type": "roll", "player_id": rng.choice(others), "value": rng.die()},
        {"type": "move", "player_id": rng.choice(others), "token_index": 0},
        {"type": "roll", "player_id": "nobody", "value": 3},
        {"type": "forfeit", "player_id": "nobody"},
        {"type": "timeout", "dice_value": 2, "turn_number": state.turn_number - 1},
        {"type": "jump", "player_id": current},
        {"type": "roll", "player_id": current},
        {"type": "move", "token_index": 0},
        {"type": "forfeit"},
        {},
    ]
    if state.phase is TurnPhase.AWAITING_ROLL:
        options += [
            {"type": "move", "player_id": current, "token_index": 0},
            {"type": "roll", "player_id": current, "value": rng.choice([0, 7, -1, "4", None, True])},
            {"type": "timeout", "turn_number": state.turn_number},
            {"type": "timeout", "dice_value": rng.choice([0, 7]), "turn_number": state.turn_number},
        ]
    else:
        options += [
            {"type": "roll", "player_id": current, "value": rng.die()},
            {"type": "move", "player_id": current, "token_index": rng.choice([-1, state.rules.tokens_per_player, 9, "0", None, True])},
        ]
        if stuck:
            options.append({"type": "move", "player_id": current, "token_index": rng.choice(stuck)})
    if out:
        options.append({"type": "forfeit", "player_id": rng.choice(out)})
    return rng.choice(options)


# ---------------------------------------------------------------------------
# Writing the file
# ---------------------------------------------------------------------------


def dumps(vectors: dict[str, Any]) -> str:
    """JSON with one step per line, so a rules change shows up as a readable diff."""

    def c(value: Any) -> str:
        return json.dumps(value, separators=(",", ":"), ensure_ascii=True)

    lines = ["{"]
    keys = list(vectors)
    for k, key in enumerate(keys):
        tail = "," if k < len(keys) - 1 else ""
        value = vectors[key]
        if key in ("setups", "snapshots"):
            lines.append(f"{c(key)}:[")
            lines += [c(v) + ("," if i < len(value) - 1 else "") for i, v in enumerate(value)]
            lines.append("]" + tail)
        elif key == "games":
            lines.append(f"{c(key)}:[")
            for g, game in enumerate(value):
                head = {k2: v2 for k2, v2 in game.items() if k2 not in ("steps", "final")}
                lines.append(c(head)[:-1] + ',"steps":[')
                steps = game["steps"]
                lines += [c(s) + ("," if i < len(steps) - 1 else "") for i, s in enumerate(steps)]
                lines.append('],"final":' + c(game["final"]) + "}" + ("," if g < len(value) - 1 else ""))
            lines.append("]" + tail)
        else:
            lines.append(f"{c(key)}:{c(value)}{tail}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    path = Path(argv[1]) if len(argv) > 1 else VECTORS_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    text = dumps(build_vectors())
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
