"""
Shared test vectors: the rules of this engine written down as JSON.

The Flutter app has a Dart copy of this engine for games played on the phone
(vs AI, pass-and-play). This module plays seeded games through the Python
engine, rules variations included, and records every action with what the
engine answered: the events, the error code for a refused action, the bot's
choice and full state snapshots. The Dart tests replay every vector and must
get exactly the same answers. Same vectors passing in both languages = same
rules.

The file lives at the repo root, ``shared/ludo/engine_vectors.json``.
``tests/test_vectors.py`` fails when it is out of date. After changing the
rules, regenerate it (from ``backend/core``)::

    python -m ludo_engine.vectors

Pure and deterministic like the engine: a fixed little random generator
(not Python's ``random``), so the same code always writes the same file.
"""

from __future__ import annotations

import json
import sys
from dataclasses import replace
from pathlib import Path
from typing import Any, Callable

from . import board
from .bot import choose_move
from .engine import apply_action, legal_moves, new_game
from .errors import EngineError
from .rules import Rules
from .state import GameState, GameStatus, PlayerState, PlayerStatus, TurnPhase

FORMAT = 1
VECTORS_PATH = Path(__file__).resolve().parents[3] / "shared" / "ludo" / "engine_vectors.json"

MAX_ACTIONS = 6000
CHECKPOINT_EVERY = 50


class _Rng:
    """xorshift64*: tiny, fixed, and easy to copy into any language."""

    _MASK = (1 << 64) - 1

    def __init__(self, seed: int) -> None:
        self._s = ((seed + 1) * 0x9E3779B97F4A7C15) & self._MASK or 1

    def next(self) -> int:
        s = self._s
        s ^= s >> 12
        s ^= (s << 25) & self._MASK
        s ^= s >> 27
        self._s = s
        return (s * 0x2545F4914F6CDD1D) & self._MASK

    def below(self, n: int) -> int:
        return (self.next() >> 11) % n

    def per_mille(self, chance: int) -> bool:
        return self.below(1000) < chance

    def choice(self, items: list[Any]) -> Any:
        return items[self.below(len(items))]

    def die(self) -> int:
        return self.below(6) + 1


